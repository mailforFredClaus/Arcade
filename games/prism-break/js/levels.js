export const MADE_COUNT = MADE.length;

// ---- levels built from their number (51 on) -----------------------------------------

const SHAPES = [
  // Each says whether a brick goes at (c, r) on a grid `rows` deep; c runs 0..5 (the left half and the middle column).
  (c, r, rows) => true,
  (c, r, rows) => (c + r) % 2 === 0,
  (c, r, rows) => c >= 5 - r || r > rows / 2,
  (c, r, rows) => Math.abs(c - 5) + Math.abs(r - rows / 2) <= rows / 2 + 1,
  (c, r, rows) => r % 2 === 0,
  (c, r, rows) => c % 2 === 0,
  (c, r, rows) => (c + r) % 3 !== 0,
  (c, r, rows) => c <= r,
  (c, r, rows) => (Math.floor(c / 2) + Math.floor(r / 2)) % 2 === 0,
  (c, r, rows) => Math.abs(c - 2.5) + Math.abs(r - rows / 2) > 2,
];

function built(n) {
  const R = new Rand(7000 + n * 131);
  const hard = Math.min(1, (n - MADE_COUNT) / 60);
  const rows = 6 + R.int(5);
  const shape = SHAPES[R.int(SHAPES.length)];
  const palette = 'roygtbpk'.split('').sort(() => R.next() - 0.5).slice(0, 3 + R.int(3));
  const banded = R.next() < 0.5;
  const map = ['...........'];
  for (let r = 0; r < rows; r++) {
    let half = '';
    for (let c = 0; c <= 5; c++) {
      if (!shape(c, r, rows)) { half += '.'; continue; }
      let ch = palette[(banded ? r : c + r) % palette.length];
      const roll = R.next();
      if (roll < 0.05) ch = '*';
      else if (roll < 0.08) ch = '?';
      else if (roll < 0.08 + 0.1 * hard) ch = '@';
      else if (roll < 0.2 + 0.3 * hard) ch = ch.toUpperCase();
      else if (roll < 0.24 + 0.32 * hard) ch = '~';
      // A piece of steel now and then, but never two together, so nothing is ever walled in.
      else if (roll > 0.965 && r > 0 && c > 0 && c < 5 && !half.endsWith('#') && map[map.length - 1][c] !== '#') ch = '#';
      half += ch;
    }
    map.push(half + half.slice(0, 5).split('').reverse().join(''));
  }
  return map;
}

// Everything about level n: { n, name, world, map, speed, bad, drops }.
export function levelFor(n) {
  n = Math.max(1, Math.floor(n) || 1);
  const made = n <= MADE_COUNT;
  const world = made ? Math.floor((n - 1) / 10) : (Math.floor((n - 1) / 10)) % WORLDS.length;
  return {
    n,
    name: made ? MADE[n - 1][0] : `Deep Space ${n - MADE_COUNT}`,
    world,
    map: made ? MADE[n - 1][1] : built(n),
    // Faster as the levels go on.
    speed: 84 + Math.min(n, 70) * 0.5,
    // Nothing nasty falls on the first few levels, and more falls while you're learning.
    bad: n > 5,
    drops: n <= 5 ? 0.17 : 0.12,
  };
}

