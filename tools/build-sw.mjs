// Writes sw.js, the service worker that keeps a copy of every game file on
// the phone so the arcade works with no signal. Run it after changing any
// file:  node tools/build-sw.mjs
// The version is a hash of all the files, so phones fetch updates by
// themselves the next time the arcade is opened with internet.

import { readdir, readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const INCLUDE = ['index.html', 'manifest.webmanifest', 'icons', 'shared', 'games'];

async function walk(rel) {
  const entries = await readdir(join(root, rel), { withFileTypes: true }).catch(() => null);
  if (!entries) return [rel];
  const out = [];
  for (const e of entries) {
    if (e.name.startsWith('.')) continue;
    out.push(...(await walk(`${rel}/${e.name}`)));
  }
  return out;
}

const files = (await Promise.all(INCLUDE.map(walk))).flat().sort();
const hash = createHash('sha256');
for (const f of files) {
  hash.update(f);
  hash.update(await readFile(join(root, f)));
}
const version = hash.digest('hex').slice(0, 12);
// Folders with an index.html can also be opened by their folder address.
const folders = files.filter((f) => f.endsWith('/index.html')).map((f) => f.slice(0, -'index.html'.length));
const urls = ['./', ...folders, ...files];

const sw = `// Generated by tools/build-sw.mjs. Do not edit by hand.
const VERSION = 'arcade-${version}';
const FILES = ${JSON.stringify(urls, null, 2)};

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(VERSION)
      .then((cache) => cache.addAll(FILES.map((f) => new Request(f, { cache: 'reload' }))))
      .then(() => self.skipWaiting()),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('arcade-') && k !== VERSION).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

// Cache first: everything is served from the phone, so it works offline and
// opens instantly. Anything not cached falls back to the network.
self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== self.location.origin) return;
  event.respondWith(
    caches.open(VERSION).then((cache) =>
      cache.match(req, { ignoreSearch: true }).then((hit) =>
        hit || fetch(req).catch(() => (req.mode === 'navigate' ? cache.match('./index.html') : Response.error())),
      ),
    ),
  );
});
`;

await writeFile(join(root, 'sw.js'), sw);
console.log(`sw.js written: ${urls.length} entries, version ${version}`);
